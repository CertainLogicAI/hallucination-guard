## If They Reply

**Positive:** Schedule call within 24hrs. Send calendar link immediately.
**Objection:** Check references/objection-handling.md for response framework.
**"Not now":** Ask "When would be a better time?" and set reminder.
**"Not interested":** Thank them, ask for referral: "Is there someone on your team who handles [topic]?"

