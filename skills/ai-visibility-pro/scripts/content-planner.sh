## Content Structure Template

Every article should follow this structure for maximum AI citation:

```markdown
# [Title that matches a question]

[Opening paragraph that directly answers the question in 2-3 sentences]

## TL;DR
[Bullet point summary — LLMs often extract this]

## [H2 sections that are themselves questions or clear topics]

### [H3 subsections for detail]

## FAQ
[3-5 related questions with concise answers]
[These are gold for LLM citation — each FAQ item can be cited independently]
```

## Optimization Checklist Per Article

- [ ] Title matches a natural language question
- [ ] First paragraph answers the question directly (no preamble)
- [ ] TL;DR section near the top
- [ ] H2/H3 headings are descriptive (not clever/cute)
- [ ] Includes at least 1 original data point, stat, or finding
- [ ] FAQ section with 3-5 related questions
- [ ] Meta description summarizes the answer (80-160 chars)
- [ ] JSON-LD Article schema markup
- [ ] Internal links to related content
- [ ] External links to authoritative sources

## Publishing & Distribution

After publishing each article:
1. Share on X with a hook that invites discussion
2. Post to relevant subreddits (r/artificial, r/SideProject, etc.)
3. Submit to HN if it contains original research
4. Update sitemap.xml
5. Update llms.txt with new page reference
6. Wait 2 weeks, then check Perplexity/ChatGPT for citation

## Monthly Review

- [ ] Check Perplexity: search your key queries, see if you're cited
- [ ] Check ChatGPT: ask it about your topic, see if it mentions you
- [ ] Update existing articles with new data/findings
- [ ] Add new FAQ items based on actual user questions
- [ ] Review analytics for most-visited pages → double down on those topics

