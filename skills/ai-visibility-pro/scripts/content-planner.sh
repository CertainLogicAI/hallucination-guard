## How LLMs Choose What to Cite

LLMs cite content that:
1. **Directly answers a question** — "How do I X?" → your article explains X
2. **Provides unique data** — original research, benchmarks, case studies
3. **Is structured clearly** — H2/H3 headings that match question phrasing
4. **Is referenced elsewhere** — backlinks from forums, Reddit, HN, other blogs

